// A3: render the `dozebox-payload@<name>.service` drop-in from a payload definition (pure; golden-tested).
import { createHash } from "node:crypto";
import { RunnerError } from "@dozebox/core/errors";
import { RESERVED_ENV, type PayloadDefinition } from "@dozebox/protocol/payload";

export const PAYLOAD_TEMPLATE_UNIT = "dozebox-payload@.service";
export const DROPIN_DIR = "/etc/systemd/system";

export type RenderedUnit = {
  /** `dozebox-payload@<name>.service`. */
  readonly unit: string;
  /** Absolute path of the drop-in, `<DROPIN_DIR>/<unit>.d/10-dozebox.conf`. */
  readonly path: string;
  readonly text: string;
  /** sha256 of `text`, for change detection. */
  readonly hash: string;
};

export type RenderOptions = {
  /** Per-payload protocol socket, exported as DOZEBOX_SOCKET. */
  readonly socketPath: string;
  /** This box's id, exported as DOZEBOX_BOX_ID. */
  readonly boxId: string;
  /** `LoadCredential=` names, from `writeCredentials`. */
  readonly credentials: ReadonlyArray<string>;
  /** The jail wrapper argv prefix (A8) when the jail is on, else empty. */
  readonly execPrefix: ReadonlyArray<string>;
};

const RESERVED: ReadonlySet<string> = new Set(RESERVED_ENV);
const NEEDS_QUOTES = /[\s"'\\$%;]/;
const DEFAULT_STOP_GRACE_SECONDS = 30;

/** Quote one word for a systemd unit line: `%` and `$` doubled, `\` and `"` escaped inside double quotes. */
function quote(word: string): string {
  const escaped = word
    .replaceAll("\\", "\\\\")
    .replaceAll('"', '\\"')
    .replaceAll("\n", "\\n")
    .replaceAll("%", "%%")
    .replaceAll("$", "$$$$");
  return word === "" || NEEDS_QUOTES.test(word) ? `"${escaped}"` : escaped;
}

function invalid(message: string): RunnerError {
  return new RunnerError("invalid_input", false, message);
}

function checkEnv(def: PayloadDefinition): ReadonlyArray<readonly [string, string]> {
  const entries = Object.entries(def.start.env ?? {}).toSorted(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  for (const [key, value] of entries) {
    if (RESERVED.has(key)) throw invalid(`payload ${def.name}: env ${key} is reserved`);
    if (value.includes("\n") || value.includes("\r")) {
      throw invalid(`payload ${def.name}: env ${key} contains a newline`);
    }
  }
  return entries;
}

export function renderUnit(def: PayloadDefinition, opts: RenderOptions): RenderedUnit {
  const name = def.name;
  const env = checkEnv(def);
  const dataDir = `/data/payloads/${name}`;
  const credDir = `/run/dozebox/credentials/${name}`;
  const reserved: ReadonlyArray<readonly [string, string]> = [
    ["DOZEBOX_SOCKET", opts.socketPath],
    ["DOZEBOX_PAYLOAD", name],
    ["DOZEBOX_BOX_ID", opts.boxId],
    ["DOZEBOX_PROTOCOL", def.protocol],
    ["DOZEBOX_DATA_DIR", dataDir],
    ["DOZEBOX_STATUS_FILE", `/run/dozebox/status/${name}.json`],
  ];
  for (const [key, value] of reserved) {
    if (value.includes("\n")) throw invalid(`payload ${name}: ${key} contains a newline`);
  }
  const hasEnvSecret = (def.secrets ?? []).some((s) => "env" in s.as);
  // EnvironmentFile= overrides Environment=, so an env secret must not carry a reserved name either.
  const reservedSecret = (def.secrets ?? []).find((s) => "env" in s.as && RESERVED.has(s.as.env));
  if (reservedSecret) throw invalid(`payload ${name}: secret ${reservedSecret.name} may not set a reserved env var`);
  const description = def.description === undefined ? "" : ` - ${def.description.replaceAll(/\s+/g, " ").trim()}`;

  const lines: string[] = [
    "# Generated by dozebox. Do not edit; it is rewritten from the payload definition.",
    "[Unit]",
    `Description=dozebox payload ${name}${description}`,
    "",
    "[Service]",
    `User=${def.user}`,
    `Group=${def.user}`,
    `WorkingDirectory=${def.start.workingDirectory ?? dataDir}`,
    "ExecStart=",
    `ExecStart=${[...opts.execPrefix, ...def.start.command].map(quote).join(" ")}`,
  ];
  for (const [key, value] of [...env, ...reserved]) lines.push(`Environment=${quote(`${key}=${value}`)}`);
  if (hasEnvSecret) lines.push(`EnvironmentFile=-${credDir}/env`);
  for (const file of opts.credentials) lines.push(`LoadCredential=${file}:${credDir}/${file}`);
  if (def.limits?.memoryMax !== undefined) lines.push(`MemoryMax=${def.limits.memoryMax}`);
  if (def.limits?.cpuWeight !== undefined) lines.push(`CPUWeight=${def.limits.cpuWeight}`);
  lines.push(`TimeoutStopSec=${def.start.stopGraceSeconds ?? DEFAULT_STOP_GRACE_SECONDS}`);

  const text = `${lines.join("\n")}\n`;
  const unit = `dozebox-payload@${name}.service`;
  return {
    unit,
    path: `${DROPIN_DIR}/${unit}.d/10-dozebox.conf`,
    text,
    hash: createHash("sha256").update(text).digest("hex"),
  };
}
