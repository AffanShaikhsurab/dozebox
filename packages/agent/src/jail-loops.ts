// A8 wiring: with the jail on, the per-uid egress rules (agents run as `<payload>-agent`); with the tripwire on, the
// decoy profile is armed and each hit pages.
import { resolve4, resolve6 } from "node:dns/promises";
import * as fsp from "node:fs/promises";
import { MINUTE } from "@dozebox/core/time";
import type { BoxConfig } from "@dozebox/protocol/config";
import type { AlertForwarder } from "./alerts/index.ts";
import type { Deps } from "./deps.ts";
import {
  APPARMOR_PROFILE,
  egressLoop,
  JAIL_EXEC_BIN,
  makeTripwire,
  renderAppArmorProfile,
  TRIPWIRE_UNITS,
  tripwireAlert,
} from "./jail/index.ts";
import type { Loop } from "./loops.ts";
import type { Logger } from "./ports/log.ts";

export async function jailLoops(c: {
  readonly deps: Deps;
  readonly box: () => BoxConfig;
  readonly jailOn: boolean;
  readonly agentUids: ReadonlyMap<string, number>;
  readonly alerts: Pick<AlertForwarder, "forward">;
  readonly log: Logger;
  readonly payloadUsers: ReadonlyArray<string>;
  readonly signal: AbortSignal;
  /** Called after the egress table is loaded, so readiness can be recomputed. */
  readonly onEgressApplied?: () => void;
}): Promise<ReadonlyArray<Loop>> {
  const { deps, box } = c;
  const loops: Loop[] = [];
  await setupHost(c, c.signal).catch((e: unknown) => c.log.log("warn", "jail setup failed", { error: e }));
  if (c.jailOn) {
    loops.push(
      egressLoop({
        exec: deps.exec,
        files: deps.files,
        config: () => ({
          enabled: box().jail.enabled,
          egress: box().jail.egress === "allowlist" ? "allowlist" : "imds-only",
          allowHosts: box().jail.allowHosts,
        }),
        uids: () => [...c.agentUids.values()],
        lookup: async (host) => [...(await resolve4(host).catch(() => [])), ...(await resolve6(host).catch(() => []))],
        onApplied: () => c.onEgressApplied?.(),
      }),
    );
  }
  if (box().tripwire.enabled) {
    const tripwire = makeTripwire({
      files: deps.files,
      now: deps.clock.now,
      chmod: fsp.chmod,
      region: deps.identity.region,
    });
    await tripwire.arm().catch((e: unknown) => c.log.log("warn", "tripwire not armed", { error: e }));
    loops.push({
      name: "tripwire",
      everyMs: MINUTE,
      tick: async () => {
        for (const hit of await tripwire.hits()) {
          const a = tripwireAlert(hit);
          await c.alerts.forward({ source: a.key, severity: a.severity, title: a.title, body: a.body });
        }
      },
    });
  }
  return loops;
}

const SUDOERS_FILE = "/etc/sudoers.d/dozebox";

/** The host side of the jail (agent-edge R2): AppArmor profile, the sudoers rule, the tripwire units. Best effort. */
async function setupHost(c: Parameters<typeof jailLoops>[0], signal: AbortSignal): Promise<void> {
  const { deps } = c;
  const run = async (argv: ReadonlyArray<string>) => {
    const r = await deps.exec.run(argv, { signal });
    if (r.code !== 0)
      c.log.log("warn", "jail setup step failed", { argv: argv.join(" "), stderr: r.stderr.slice(0, 300) });
  };
  if (c.jailOn) {
    await deps.files.writeAtomic(APPARMOR_PROFILE, renderAppArmorProfile());
    await run(["apparmor_parser", "-r", APPARMOR_PROFILE]);
    const users = [...new Set(c.payloadUsers)].toSorted();
    const rules = users.map((u) => `${u} ALL=(root) NOPASSWD: ${JAIL_EXEC_BIN} *`);
    await deps.files.writeAtomic(SUDOERS_FILE, `# Generated by dozebox.\n${rules.join("\n")}\n`);
    await run(["visudo", "-cf", SUDOERS_FILE]);
  }
  if (c.box().tripwire.enabled) {
    for (const [name, text] of Object.entries(TRIPWIRE_UNITS))
      await deps.files.writeAtomic(`/etc/systemd/system/${name}`, text);
    await run(["systemctl", "daemon-reload"]);
    await run(["systemctl", "enable", "--now", "dozebox-tripwire.socket"]);
  }
}
