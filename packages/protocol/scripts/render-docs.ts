// Markdown tables for docs/reference/protocol-v1.md, one per schema, one row per field (nested fields dotted).
import type { SchemaEntry } from "../src/registry.ts";
import { schemaFileName } from "../src/registry.ts";

type Json = { readonly [key: string]: unknown };

function asJson(value: unknown): Json {
  return typeof value === "object" && value !== null ? (value as Json) : {};
}

function constraints(s: Json): string {
  const keys = ["pattern", "minLength", "maxLength", "minimum", "maximum", "minItems", "maxItems", "format"];
  return keys
    .filter((k) => s[k] !== undefined)
    .map((k) => `${k} \`${String(s[k]).replaceAll("|", "\\|")}\``)
    .join(", ");
}

function typeName(s: Json): string {
  if (s["const"] !== undefined) return `\`${JSON.stringify(s["const"])}\``;
  if (Array.isArray(s["anyOf"])) return s["anyOf"].map((x) => typeName(asJson(x))).join(" or ");
  if (s["type"] === "array") return `array of ${typeName(asJson(s["items"]))}`;
  if (s["type"] === "object" && s["patternProperties"]) return "map";
  if (typeof s["type"] === "string") return s["type"];
  return "any";
}

function rows(s: Json, prefix: string, depth: number, out: string[]): void {
  const props = asJson(s["properties"]);
  const required = new Set(Array.isArray(s["required"]) ? (s["required"] as string[]) : []);
  for (const [name, raw] of Object.entries(props)) {
    const p = asJson(raw);
    const path = prefix + name;
    out.push(`| \`${path}\` | ${typeName(p)} | ${required.has(name) ? "yes" : "no"} | ${constraints(p)} |`);
    if (p["type"] === "object" && p["properties"] && depth < 3) rows(p, `${path}.`, depth + 1, out);
    const items = asJson(p["items"]);
    if (p["type"] === "array" && items["type"] === "object" && depth < 3) rows(items, `${path}[].`, depth + 1, out);
  }
}

export function renderDocs(entries: ReadonlyArray<SchemaEntry>): string {
  const out = [
    "# Protocol v1 reference",
    "",
    "Generated by `pnpm --filter @dozebox/protocol gen:schema` from the TypeBox schemas in `packages/protocol/src`.",
    "Do not edit by hand. Request schemas reject unknown fields; response schemas allow them (part 4 §4.15).",
    "",
  ];
  let group = "";
  for (const { title, group: g, schema } of entries) {
    if (g !== group) {
      out.push(`## ${g}`, "");
      group = g;
    }
    const s = asJson(schema);
    const strict = s["additionalProperties"] === false ? " Unknown fields are rejected." : "";
    out.push(`### ${title}`, "", `JSON Schema: \`schema/v1/${schemaFileName(title)}\`.${strict}`, "");
    const body: string[] = [];
    rows(s, "", 0, body);
    if (body.length === 0) {
      out.push("No fields.", "");
      continue;
    }
    out.push("| Field | Type | Required | Constraints |", "| --- | --- | --- | --- |", ...body, "");
  }
  return out.join("\n");
}
