// Writes docs/reference/cli.md (from the CLI's command list and help text) and docs/reference/terraform.md (from the
// `variable` and `output` blocks of terraform/*.tf). `--check` writes nothing and exits 1 when a file is out of date.
// Usage: node --conditions=@dozebox/source scripts/docs/gen-reference.ts [--check]
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { EXIT, type Command } from "../../packages/cli/src/command.ts";
import { COMMANDS } from "../../packages/cli/src/commands/index.ts";
import { helpText } from "../../packages/cli/src/main.ts";
import { declarations, stringValue, type HclDeclaration } from "./hcl.ts";

export const CLI_REFERENCE = "docs/reference/cli.md";
export const TERRAFORM_REFERENCE = "docs/reference/terraform.md";
const REGENERATE = "node --conditions=@dozebox/source scripts/docs/gen-reference.ts";
const banner = (what: string): string =>
  `<!-- Generated by scripts/docs/gen-reference.ts from ${what}. Do not edit; run \`${REGENERATE}\`. -->`;

const cell = (text: string): string =>
  text.replace(/\|/g, "\\|").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/\s+/g, " ").trim();
const code = (text: string): string => `\`${text.replace(/\s+/g, " ").trim().replace(/\|/g, "\\|")}\``;

const EXIT_MEANING: Readonly<Record<keyof typeof EXIT, string>> = {
  ok: "Done.",
  problem: "The command ran and found a problem, for example `doctor` found a failing check.",
  usage: "Usage error: an unknown flag, a missing argument or a bad value.",
  notSetUp: "Not set up: there is no stack, or the stack lacks a Terraform output. Run `dozebox setup`.",
  aws: "AWS or the network failed after retries.",
  refused: "The control function refused: the box is frozen, over budget, or the request conflicts with its state.",
  tryLater: "Try again later: the wake budget is used up or a lock is held.",
  interrupted: "Interrupted with Ctrl-C.",
};

function globalOptions(): ReadonlyArray<readonly [string, string]> {
  const lines = helpText(COMMANDS).split("\n");
  const start = lines.indexOf("Global options:");
  const rows: Array<readonly [string, string]> = [];
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === "") break;
    const [flag = "", ...rest] = line.trim().split(/\s{2,}/);
    rows.push([flag, rest.join(" ")]);
  }
  return rows;
}

function optionRows(options: Command["options"]): ReadonlyArray<string> {
  return Object.entries(options).map(([name, o]) => {
    const flag = `${o.short === undefined ? "" : `-${o.short}, `}--${name}`;
    const notes = [
      ...(o.multiple === true ? ["repeatable"] : []),
      ...(o.default === undefined ? [] : [`default \`${String(o.default)}\``]),
    ];
    return `| ${code(flag)} | ${o.type === "string" ? "value" : "flag"} | ${notes.join(", ")} |`;
  });
}

function commandSection(c: Command): ReadonlyArray<string> {
  const rows = optionRows(c.options);
  return [
    `### \`dozebox ${c.name}\``,
    "",
    cell(c.summary),
    "",
    c.mutates
      ? "Changes state. Honours `--dry-run` and asks before it acts (`--yes` skips the question)."
      : "Read-only.",
    ...(rows.length === 0 ? [] : ["", "| Option | Takes | Notes |", "| --- | --- | --- |", ...rows]),
    "",
  ];
}

const commandIndex = (list: ReadonlyArray<Command>): ReadonlyArray<string> => [
  "| Command | What it does |",
  "| --- | --- |",
  ...list.map((c) => `| ${code(`dozebox ${c.name}`)} | ${cell(c.summary)} |`),
  "",
];

export function renderCliReference(commands: ReadonlyArray<Command> = COMMANDS): string {
  const operator = commands.filter((c) => c.mode !== "box");
  const box = commands.filter((c) => c.mode !== "operator");
  return [
    banner("the CLI's command list"),
    "",
    "# CLI reference",
    "",
    "`dozebox` runs in operator mode on a machine with AWS credentials, and in box mode on the box (it detects",
    "`/run/dozebox/`). The same command name can exist in both modes with a different meaning, such as `status`.",
    "Flags that are not listed for a command are a usage error (exit code 2).",
    "",
    "## Global options",
    "",
    "| Flag | Meaning |",
    "| --- | --- |",
    ...globalOptions().map(([flag, text]) => `| ${code(flag)} | ${cell(text)} |`),
    "",
    "## Exit codes",
    "",
    "| Code | Meaning |",
    "| --- | --- |",
    ...Object.entries(EXIT).map(([key, n]) => `| ${n} | ${cell(EXIT_MEANING[key as keyof typeof EXIT])} |`),
    "",
    "## Operator commands",
    "",
    ...commandIndex(operator),
    ...operator.flatMap(commandSection),
    "## Box commands",
    "",
    ...commandIndex(box),
    ...box.flatMap(commandSection),
  ]
    .join("\n")
    .replace(/\n+$/, "\n");
}

type Row = {
  readonly name: string;
  readonly description: string;
  readonly type: string;
  readonly fallback: string | null;
};

function attr(d: HclDeclaration, name: string): string | null {
  for (const i of d.items) if (i.kind === "attr" && i.name === name) return i.value;
  return null;
}

function rules(d: HclDeclaration): ReadonlyArray<string> {
  const out: string[] = [];
  for (const i of d.items) {
    if (i.kind !== "block" || i.name !== "validation") continue;
    const msg = /^\s*error_message\s*=\s*(.+)$/m.exec(i.body)?.[1];
    if (msg !== undefined) out.push(stringValue(msg.trim()));
  }
  return out;
}

function dedent(text: string): string {
  const [first = "", ...rest] = text.split("\n");
  return [first, ...rest.map((l) => (l.startsWith("  ") ? l.slice(2) : l))].join("\n");
}

const rank = (f: string): number => (f === "variables.tf" || f === "outputs.tf" ? 0 : 1);

function terraformFiles(root: string): ReadonlyArray<string> {
  const dir = join(root, "terraform");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".tf"))
    .toSorted((a, b) => rank(a) - rank(b) || a.localeCompare(b));
}

export function renderTerraformReference(root: string): string {
  const all = terraformFiles(root).flatMap((f) => declarations(readFileSync(join(root, "terraform", f), "utf8")));
  const variables = all.filter((d) => d.kind === "variable");
  const outputs = all.filter((d) => d.kind === "output");
  const rows: Row[] = variables.map((d) => ({
    name: d.name,
    description: stringValue(attr(d, "description") ?? ""),
    type: attr(d, "type") ?? "any",
    fallback: attr(d, "default"),
  }));
  const shapes = rows.filter((r) => r.type.includes("\n"));
  const ruled = variables.filter((d) => rules(d).length > 0);
  return [
    banner("terraform/*.tf"),
    "",
    "# Terraform reference",
    "",
    "Every input and output of the module in `terraform/`. An input with no default is required.",
    "",
    "## Inputs",
    "",
    "| Name | Type | Default | Required | Description |",
    "| --- | --- | --- | --- | --- |",
    ...rows.map((r) => {
      const type = r.type.includes("\n")
        ? `${r.type.slice(0, r.type.indexOf("(")).trim() || "object"} (see below)`
        : r.type;
      return `| ${code(r.name)} | ${code(type)} | ${r.fallback === null ? "n/a" : code(r.fallback)} | ${r.fallback === null ? "yes" : "no"} | ${cell(r.description)} |`;
    }),
    "",
    "## Object inputs",
    "",
    ...shapes.flatMap((r) => [`### ${r.name}`, "", "```hcl", dedent(r.type), "```", ""]),
    "## Input rules",
    "",
    "Terraform rejects a value that breaks one of these at plan time.",
    "",
    ...ruled.flatMap((d) => rules(d).map((m) => `- ${code(d.name)}: ${cell(m)}`)),
    "",
    "## Outputs",
    "",
    "| Name | Description |",
    "| --- | --- |",
    ...outputs.map((d) => `| ${code(d.name)} | ${cell(stringValue(attr(d, "description") ?? ""))} |`),
    "",
  ].join("\n");
}

function generateReference(root: string): Readonly<Record<string, string>> {
  return { [CLI_REFERENCE]: renderCliReference(), [TERRAFORM_REFERENCE]: renderTerraformReference(root) };
}

export function writeReference(root: string): ReadonlyArray<string> {
  const files = generateReference(root);
  mkdirSync(join(root, "docs", "reference"), { recursive: true });
  for (const [path, text] of Object.entries(files)) writeFileSync(join(root, path), text);
  return Object.keys(files);
}

/** One message per generated file that is missing or differs from what the sources produce now. */
export function checkReference(root: string): ReadonlyArray<string> {
  const problems: string[] = [];
  for (const [path, text] of Object.entries(generateReference(root))) {
    const file = join(root, path);
    if (!existsSync(file)) problems.push(`${path} is missing; run \`${REGENERATE}\``);
    else if (readFileSync(file, "utf8") !== text) problems.push(`${path} is out of date; run \`${REGENERATE}\``);
  }
  return problems;
}

if (import.meta.main) {
  const root = join(import.meta.dirname, "..", "..");
  if (process.argv.includes("--check")) {
    const problems = checkReference(root);
    for (const p of problems) process.stderr.write(`${p}\n`);
    process.exitCode = problems.length === 0 ? 0 : 1;
  } else {
    for (const path of writeReference(root)) process.stdout.write(`wrote ${path}\n`);
  }
}
