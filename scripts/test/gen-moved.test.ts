test("the data volume is moved, never removed", () => {
  const plan = planMoves(["aws_ebs_volume.data"]);
  assert.deepEqual(plan.removed, []);
  assert.deepEqual(plan.moved, [{ from: "aws_ebs_volume.data", to: "module.dozebox.aws_ebs_volume.data[0]" }]);
});

test("an address without a rule is listed in unknown and nowhere else", () => {
  const plan = planMoves(["aws_vpc.box", "aws_new_thing.x", "module.other.aws_vpc.box"]);
  assert.deepEqual(plan.unknown, ["aws_new_thing.x", "module.other.aws_vpc.box"]);
  assert.equal(plan.moved.length, 1);
  assert.deepEqual(plan.removed, []);
});

test("the module name is a parameter", () => {
  const plan = planMoves(["aws_vpc.box"], { module: "runner" });
  assert.deepEqual(plan.moved, [{ from: "aws_vpc.box", to: "module.runner.aws_vpc.box[0]" }]);
});

test("input order and repeats do not change the plan", () => {
  const forward = planMoves(FIXTURE);
  assert.deepEqual(planMoves(FIXTURE.toReversed().concat(FIXTURE)), forward);
});

test("renderMoved writes one block per move and per removal, moved first", () => {
  const text = renderMoved(planMoves(["aws_vpc.box", "aws_ebs_volume.data", "aws_cloudtrail.tripwire[0]"]));
  assert.match(text, /^# Generated by scripts\/gen-moved\.ts/);
  assert.equal(text.match(/^moved \{$/gm)?.length, 2);
  assert.equal(text.match(/^removed \{$/gm)?.length, 1);
  assert.ok(text.endsWith("}\n"));
  assert.ok(
    text.includes("moved {\n  from = aws_ebs_volume.data\n  to   = module.dozebox.aws_ebs_volume.data[0]\n}"),
    text,
  );
  assert.ok(
    text.includes("removed {\n  from = aws_cloudtrail.tripwire\n\n  lifecycle {\n    destroy = false\n  }\n}"),
    text,
  );
  assert.ok(text.indexOf("moved {") < text.indexOf("removed {"));
  assert.ok(text.indexOf("aws_ebs_volume.data") < text.indexOf("aws_vpc.box"));
});

test("the CLI reads stdin and writes HCL on stdout", () => {
  const run = spawnSync(process.execPath, [SCRIPT, "--module", "dz"], { input: FIXTURE.join("\n"), encoding: "utf8" });
  assert.equal(run.status, 0, run.stderr);
  assert.match(run.stdout, /to {3}= module\.dz\.aws_vpc\.box\[0\]/);
});

test("the CLI exits non-zero and lists unknown addresses on stderr", () => {
  const run = spawnSync(process.execPath, [SCRIPT], { input: "aws_vpc.box\naws_mystery.thing\n", encoding: "utf8" });
  assert.equal(run.status, 1);
  assert.equal(run.stdout, "");
  assert.match(run.stderr, /no rule for aws_mystery\.thing/);
});

test(
  "every resource of the legacy root has a rule",
  { skip: !existsSync(join(ROOT, "legacy/terraform/runner")) },
  () => {
    const missing = [...declared(join(ROOT, "legacy/terraform/runner"))].filter(
      (a) => !LEGACY_RULES.some((r) => r.from === a),
    );
    assert.deepEqual(missing, []);
  },
);

test("every rule names a legacy resource and a resource the module declares", () => {
  const module = declared(join(ROOT, "terraform"));
  const badTargets = LEGACY_RULES.flatMap((r) => (r.to === null ? [] : [r.to.replace(/\[.*$/, "")])).filter(
    (to) => !module.has(to),
  );
  assert.deepEqual(badTargets, []);
  assert.equal(new Set(LEGACY_RULES.map((r) => r.from)).size, LEGACY_RULES.length, "duplicate rule");
});
