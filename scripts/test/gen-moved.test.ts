import { strict as assert } from "node:assert";
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { LEGACY_RULES, planMoves, renderMoved } from "../gen-moved.ts";

const FIXTURE = readFileSync(join(import.meta.dirname, "fixtures", "legacy-state-list.txt"), "utf8").split("\n");
const SCRIPT = join(import.meta.dirname, "..", "gen-moved.ts");
const ROOT = join(import.meta.dirname, "..", "..");
const RESOURCE = /^resource\s+"([a-z0-9_]+)"\s+"([A-Za-z0-9_-]+)"/gm;

function declared(dir: string): Set<string> {
  const found = new Set<string>();
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".tf"))) {
    for (const m of readFileSync(join(dir, file), "utf8").matchAll(RESOURCE)) found.add(`${m[1]}.${m[2]}`);
  }
  return found;
}

